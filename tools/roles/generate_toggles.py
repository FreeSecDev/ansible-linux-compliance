"""Generate the topic toggle defaults, argument specs and variable reference from the catalogue.

ADR 0011 gives every control family a topic toggle ``linux_compliance_<family>_enabled`` and every
catalogued rule a rule toggle ``linux_compliance_rule_<rule_short_id>_enabled`` that follows its
family toggle unless it is set. This tool derives, from ``roles/remediate/vars/rules.yml``:

* the topic toggles of the families and of the umbrellas that group them (ADR 0011, topic split
  of FREES-53) in ``defaults/main.yml`` of the ``remediate`` and the ``audit`` role, every one
  ``true``;
* their entries in the ``main`` entry point of ``meta/argument_specs.yml`` of both roles, typed
  ``bool`` with descriptions;
* the variable reference ``docs/remediation-variables.md``, which lists every topic toggle and
  every rule toggle, per family, with the rules of other families that a toggle switches off
  through subsystem tags (FREES-165).

Rule toggles are not declared in the roles (amendment of FREES-53 to ADR 0011): with the full
catalogue there are more than a thousand, and declaring each as a default and an argument spec
made every role run several seconds slower per host. A rule toggle that is not set resolves to its
family toggle in ``plugins/module_utils/compliance/toggles.py``, exactly as the former generated
default did, and that module validates every rule toggle that is set. An old toggle in the files
is removed.

Every other variable and option of those files is kept as it is, in its order, and the topic
toggles follow it in registry order. The two YAML files are written in one canonical style, which
is checked to load back to the same data. With ``--check`` nothing is written: the tool prints a
unified diff of every file that differs and exits with status 1, which is how CI detects drift.
"""

