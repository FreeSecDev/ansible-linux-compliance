class GenerationError(Exception):
    """The catalogue or a file to update cannot be turned into the generated output."""


def is_generated(name: str) -> bool:
    """Return whether ``name`` is a toggle that this tool owns (a family or rule toggle)."""
    match = re.fullmatch(toggles.TOGGLE_PATTERN, name)
    return match is not None and not toggles.in_namespace(match.group(1), toggles.ROLE_NAMESPACES)


def _load_yaml(path: Path) -> object:
    try:
        return cast("object", yaml.safe_load(path.read_text(encoding="utf-8")))
    except (OSError, yaml.YAMLError) as error:
        message = f"{path}: cannot be read as YAML: {error}"
        raise GenerationError(message) from error


def _mapping(value: object, where: str) -> dict[str, object]:
    mapping = toggles.as_mapping(value)
    if mapping is None:
        message = f"{where} must be a mapping"
        raise GenerationError(message)
    return mapping


def load_catalogue(path: Path) -> toggles.Catalogue:
    """Load and validate the catalogue and the family registry in ``path``."""
    data = _mapping(_load_yaml(path), str(path))
    errors = toggles.Errors()
    loaded = toggles.load_catalogue(
        data.get(RULES_KEY), data.get(AUDIT_ONLY_KEY), data.get(FAMILIES_KEY), {}, errors
    )
    if errors.items:
        message = f"{path} is invalid: " + "; ".join(errors.items)
        raise GenerationError(message)
    return loaded


def toggle_defaults(catalogue: toggles.Catalogue) -> dict[str, object]:
    """Return the generated topic toggle defaults, in registry order."""
    return {toggles.toggle_name(name): True for name in catalogue.families}


def _members(catalogue: toggles.Catalogue, family: str) -> list[toggles.Rule]:
    return [rule for rule in catalogue.rules if rule["family"] == family]


def _rule_count(catalogue: toggles.Catalogue, family: str) -> int:
    return len(_members(catalogue, family))


def _native_count(catalogue: toggles.Catalogue, family: str) -> int:
    return sum(toggles.is_native(rule) for rule in _members(catalogue, family))


def family_spec(catalogue: toggles.Catalogue, family: str) -> dict[str, object]:
    """Return the argument spec of the topic toggle of ``family``."""
    description = [
        f"Topic toggle of the {family} control family (ADR 0011).",
        "When false, every rule of the family whose rule toggle is not set is off.",
        "Remediation cleans such a rule up when the state ledger records it as applied.",
        "The audit excludes it and reports it as disabled, naming this variable.",
    ]
    if catalogue.families[family]:
        description.extend(
            [
                "The family is disruptive: remediation applies and cleans up its rules only",
                "when linux_compliance_remediate_allow_disruptive names it.",
            ]
        )
    description.extend(
        [
            (
                f"Catalogued rules: {_rule_count(catalogue, family)}, "
                f"with a native remediation: {_native_count(catalogue, family)}."
            ),
            "Rule toggles linux_compliance_rule_<id>_enabled are not declared here; see",
            "docs/remediation-variables.md.",
            GENERATED_NOTE,
        ]
    )
    return {"type": "bool", "default": True, "description": description}


def toggle_specs(catalogue: toggles.Catalogue) -> dict[str, dict[str, object]]:
    """Return the generated argument spec of every topic toggle, in the order of the defaults."""
    return {
        toggles.toggle_name(family): family_spec(catalogue, family) for family in catalogue.families
    }


def defaults(catalogue: toggles.Catalogue, current: dict[str, object]) -> dict[str, object]:
    """Return ``current`` without its old toggles, followed by the generated toggle defaults."""
    kept = {name: value for name, value in current.items() if not is_generated(name)}
    kept.update(toggle_defaults(catalogue))
    return kept


def allow_list_choices(catalogue: toggles.Catalogue) -> list[str]:
    """Return the choices of the disruptive allow-list: every disruptive family, sorted."""
    return sorted(name for name, disruptive in catalogue.families.items() if disruptive)


def specs(catalogue: toggles.Catalogue, current: dict[str, object]) -> dict[str, object]:
    """Return ``current`` with the generated toggle options in its ``main`` entry point.

    When the entry point declares the disruptive allow-list, its ``choices`` are set to the
    disruptive families of the registry, so the list cannot fall behind the registry.
    """
    entry_points = _mapping(current.get("argument_specs"), "argument_specs")
    main = _mapping(entry_points.get(ENTRY_POINT), f"argument_specs.{ENTRY_POINT}")
    options = _mapping(main.get("options"), f"argument_specs.{ENTRY_POINT}.options")
    generated: dict[str, object] = {
        name: value for name, value in options.items() if not is_generated(name)
    }
    if ALLOW_LIST in generated:
        allow_list = _mapping(generated[ALLOW_LIST], ALLOW_LIST)
        allow_list["choices"] = allow_list_choices(catalogue)
        generated[ALLOW_LIST] = allow_list
    generated.update(toggle_specs(catalogue))
    main["options"] = generated
    entry_points[ENTRY_POINT] = main
    result = dict(current)
    result["argument_specs"] = entry_points
    return result


def _rule_rows(catalogue: toggles.Catalogue, family: str) -> list[str]:
    members = _members(catalogue, family)
    lines = [f"### `{family}`", ""]
    if not members:
        return [*lines, "No rule of the pinned profiles belongs to this family.", ""]
    lines.extend(["| Variable | Rule | Strategy |", "|---|---|---|"])
    lines.extend(
        f"| `{rule['toggle']}` | `{toggles.rule_short_id(str(rule['rule_id']))}` | "
        f"`{rule['revert_strategy']}` |"
        for rule in members
    )
    return [*lines, ""]


def reference(catalogue: toggles.Catalogue) -> str:
    """Return the Markdown variable reference of every toggle."""
    lines: list[str] = list(REFERENCE_INTRO)
    for family, disruptive in catalogue.families.items():
        count = _rule_count(catalogue, family)
        native = _native_count(catalogue, family)
        lines.append(
            f"| `{toggles.toggle_name(family)}` | `{family}` | {'yes' if disruptive else 'no'} | "
            f"`true` | {count} | {native} | {count - native} |"
        )
    lines.extend(
        [
            "",
            "## Rule toggles",
            "",
            "Every rule toggle defaults to the value of the topic toggle of its family, and the",
            "rule column holds the short rule identifier. The strategy is the revert strategy of",
            "a rule with a native remediation, or `audit_only`.",
            "",
        ]
    )
    for family in catalogue.families:
        lines.extend(_rule_rows(catalogue, family))
    return "\n".join(lines).rstrip("\n") + "\n"


def _key(key: str) -> str:
    if PLAIN_KEY.fullmatch(key) and key.lower() not in RESERVED_WORDS:
        return key
    return json.dumps(key)


def _scalar(value: object, *, plain: bool) -> str:
    if isinstance(value, str):
        bare = plain and PLAIN_VALUE.fullmatch(value) and value not in RESERVED_WORDS
        return value if bare else json.dumps(value)
    if isinstance(value, bool) or value is None:
        return json.dumps(value)
    if isinstance(value, int):
        return str(value)
    return _empty_collection(value)


def _empty_collection(value: object) -> str:
    empty: dict[type, str] = {dict: "{}", list: "[]"}
    if type(value) in empty and not value:
        return empty[type(value)]
    message = f"cannot render a value of type {type(value).__name__}"
    raise GenerationError(message)


def _emit_scalar(prefix: str, value: object, indent: int, out: list[str], *, plain: bool) -> None:
    line = f"{prefix} {_scalar(value, plain=plain)}"
    if len(line) <= MAX_LINE:
        out.append(line)
        return
    continuation = " " * (indent + 2) + str(value)
    foldable = isinstance(value, str) and value == value.strip() and value.isprintable()
    if not foldable or len(continuation) > MAX_LINE:
        message = f"cannot render within {MAX_LINE} characters: {line[:80]}"
        raise GenerationError(message)
    out.extend([f"{prefix} >-", continuation])


def _non_empty(value: object, kind: type) -> bool:
    return isinstance(value, kind) and bool(value)


def _emit_value(
    key: str, value: object, indent: int, out: list[str], plain_keys: frozenset[str]
) -> None:
    prefix = " " * indent + _key(key) + ":"
    if _non_empty(value, dict):
        out.append(prefix)
        _emit_mapping(cast("dict[object, object]", value), indent + 2, out, plain_keys)
    elif _non_empty(value, list):
        out.append(prefix)
        _emit_sequence(cast("list[object]", value), indent + 2, out, plain_keys)
    else:
        _emit_scalar(prefix, value, indent, out, plain=key in plain_keys)


def _emit_mapping(
    mapping: dict[object, object], indent: int, out: list[str], plain_keys: frozenset[str]
) -> None:
    for key, value in mapping.items():
        if not isinstance(key, str):
            message = f"cannot render the key {key!r}"
            raise GenerationError(message)
        _emit_value(key, value, indent, out, plain_keys)


def _emit_sequence(
    items: list[object], indent: int, out: list[str], plain_keys: frozenset[str]
) -> None:
    for item in items:
        if _non_empty(item, dict):
            lines: list[str] = []
            _emit_mapping(cast("dict[object, object]", item), indent + 2, lines, plain_keys)
            lines[0] = " " * indent + "- " + lines[0][indent + 2 :]
            out.extend(lines)
        elif _non_empty(item, list):
            message = "cannot render a sequence of non-empty sequences"
            raise GenerationError(message)
        else:
            _emit_scalar(" " * indent + "-", item, indent, out, plain=True)


def render_yaml(data: dict[str, object], plain_keys: frozenset[str] = PLAIN_VALUE_KEYS) -> str:
    """Return ``data`` as YAML in the canonical style, checked to load back to ``data``.

    String values of the keys in ``plain_keys`` are written without quotes when they are plain
    lower-case words; every other string is quoted. A mapping inside a sequence starts on the
    line of its dash.
    """
    out: list[str] = ["---"]
    _emit_mapping(cast("dict[object, object]", data), 0, out, plain_keys)
    text = "\n".join(out) + "\n"
    if yaml.safe_load(text) != data:
        message = "the rendered YAML does not load back to the same data"
        raise GenerationError(message)
    return text


def outputs(root: Path) -> dict[Path, str]:
    """Return the generated content of every output file below ``root``."""
    catalogue = load_catalogue(root / CATALOGUE)
    generated: dict[Path, str] = {}
    for defaults_file, specs_file in ROLE_FILES:
        current_defaults = _mapping(_load_yaml(root / defaults_file), str(defaults_file))
        current_specs = _mapping(_load_yaml(root / specs_file), str(specs_file))
        generated[defaults_file] = render_yaml(defaults(catalogue, current_defaults))
        generated[specs_file] = render_yaml(specs(catalogue, current_specs))
    generated[REFERENCE] = reference(catalogue)
    return generated


def _current(path: Path) -> str:
    return path.read_text(encoding="utf-8") if path.is_file() else ""


def drift(root: Path, generated: dict[Path, str]) -> list[str]:
    """Return a unified diff line list for every generated file that differs on disk."""
    lines: list[str] = []
    for relative, content in generated.items():
        current = _current(root / relative)
        if current != content:
            lines.extend(
                difflib.unified_diff(
                    current.splitlines(),
                    content.splitlines(),
                    fromfile=f"{relative} (on disk)",
                    tofile=f"{relative} (generated)",
                    lineterm="",
                )
            )
    return lines


def main(argv: Sequence[str] | None = None) -> int:
    """Command-line entry point; returns the process exit status."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path())
    parser.add_argument("--check", action="store_true", help="report drift instead of writing")
    arguments = parser.parse_args(argv)
    root = cast("Path", arguments.root)
    try:
        generated = outputs(root)
    except GenerationError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    if arguments.check:
        differences = drift(root, generated)
        if differences:
            print("\n".join(differences), file=sys.stderr)
            print("error: the toggles are out of date; run make toggles", file=sys.stderr)
            return 1
        print(f"toggles match {CATALOGUE}")
        return 0
    for relative, content in generated.items():
        (root / relative).write_text(content, encoding="utf-8")
    print(f"generated {', '.join(str(path) for path in generated)} from {CATALOGUE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
