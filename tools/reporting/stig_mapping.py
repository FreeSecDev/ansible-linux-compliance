"""The DISA STIG to ComplianceAsCode mapping that the checklist export reads (FREES-146).

``content/stig-mapping.json`` is generated by ``tools/content/generate_stig_mapping.py`` from the
pinned, digest-verified ComplianceAsCode datastreams alone and checked in CI against them. For each
ComplianceAsCode STIG profile it records the DISA release the profile implements (``V1R5``) and,
for each STIG ID (the DISA rule ``version``, ``Rule_Ver`` in a checklist), the ComplianceAsCode
rules that check it. It holds identifiers only.

A ComplianceAsCode scan run is exported with an entry only when the run's benchmark, profile and
content SHA-256 are the entry's: a scan of other ComplianceAsCode content is never exported with
this mapping. The DISA group and rule IDs come from the DISA content given at export time, joined
on the STIG ID (:mod:`tools.reporting.checklist_mapped`).

The file is read strictly: bounded, strict JSON, exact key sets, identifiers checked against
their patterns, every list sorted and unique, and every rule of an entry listed once at most among
the rules without a STIG ID.
"""

import re
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from types import MappingProxyType
from typing import Final

from tools.reporting.common import (
    InvalidInputError,
    as_list,
    as_object,
    clean_text,
    load_json,
    read_input,
)

DEFAULT_PATH: Final[Path] = Path(__file__).resolve().parents[2] / "content" / "stig-mapping.json"
MAX_BYTES: Final[int] = 16 * 1024 * 1024
SCHEMA_VERSION: Final[int] = 1
DOCUMENT_KEYS: Final[frozenset[str]] = frozenset(
    {"schema_version", "generator", "source", "join_key", "datastreams"}
)
STREAM_KEYS: Final[frozenset[str]] = frozenset(
    {"name", "file_name", "sha256", "benchmark_id", "benchmark_version", "profiles"}
)
PROFILE_KEYS: Final[frozenset[str]] = frozenset(
    {"profile_id", "stig_release", "stig_ids", "rules_without_stig_id"}
)
STIG_ID: Final[re.Pattern[str]] = re.compile(r"[A-Z][A-Z0-9]{1,15}-[0-9]{2}-[0-9]{6}")
STIG_RELEASE: Final[re.Pattern[str]] = re.compile(r"V([0-9]{1,3})R([0-9]{1,3})")
XCCDF_ID: Final[re.Pattern[str]] = re.compile(r"xccdf_[A-Za-z0-9_.+-]{1,250}")
SHA256: Final[re.Pattern[str]] = re.compile(r"[0-9a-f]{64}")
NAME: Final[re.Pattern[str]] = re.compile(r"[A-Za-z0-9][A-Za-z0-9._+-]{0,127}")


@dataclass(frozen=True)
class ProfileMapping:
    """The mapping of one ComplianceAsCode STIG profile of one pinned datastream.

    Attributes:
        datastream: The manifest name of the datastream, for example ``ubuntu2404``.
        file_name: The datastream file name.
        content_sha256: The SHA-256 of the datastream the mapping was generated from.
        benchmark_id: The ComplianceAsCode benchmark ID.
        benchmark_version: The ComplianceAsCode benchmark version.
        profile_id: The ComplianceAsCode profile ID.
        stig_release: The DISA release that the profile implements, ``V<n>R<n>``.
        checks: The ComplianceAsCode rules of each STIG ID.
        unmapped_rules: The selected rules of the profile that reference no STIG ID.
    """

    datastream: str
    file_name: str
    content_sha256: str
    benchmark_id: str
    benchmark_version: str
    profile_id: str
    stig_release: str
    checks: Mapping[str, tuple[str, ...]]
    unmapped_rules: tuple[str, ...]

    def rules_of(self, stig_id: str) -> tuple[str, ...]:
        """Return the ComplianceAsCode rules that check ``stig_id``, or none."""
        return self.checks.get(stig_id, ())

    def mapped_rules(self) -> frozenset[str]:
        """Return every ComplianceAsCode rule that checks at least one STIG ID."""
        return frozenset(rule for rules in self.checks.values() for rule in rules)


@dataclass(frozen=True)
class StigMapping:
    """Every profile mapping of the mapping file, and where it was read from."""

    path: str
    profiles: tuple[ProfileMapping, ...]

    def find(self, benchmark_id: str, profile_id: str) -> ProfileMapping | None:
        """Return the mapping of ``benchmark_id`` and ``profile_id``, or ``None``."""
        for profile in self.profiles:
            if (profile.benchmark_id, profile.profile_id) == (benchmark_id, profile_id):
                return profile
        return None


def _exact(table: dict[str, object], keys: frozenset[str], where: str) -> None:
    if frozenset(table) != keys:
        message = f"{where} must have exactly the keys {', '.join(sorted(keys))}"
        raise InvalidInputError(message)


def _identifier(value: object, pattern: re.Pattern[str], where: str) -> str:
    if not isinstance(value, str) or pattern.fullmatch(value) is None:
        message = f"{where} is not a valid identifier"
        raise InvalidInputError(message)
    return value


def _sorted_identifiers(value: object, pattern: re.Pattern[str], where: str) -> tuple[str, ...]:
    items = tuple(
        _identifier(item, pattern, f"{where}[{index}]")
        for index, item in enumerate(as_list(value, where))
    )
    if list(items) != sorted(set(items)):
        message = f"{where} must be sorted and unique"
        raise InvalidInputError(message)
    return items


def _checks(value: object, where: str) -> Mapping[str, tuple[str, ...]]:
    table = as_object(value, where)
    if not table or list(table) != sorted(table):
        message = f"{where} must be a non-empty object with sorted STIG IDs"
        raise InvalidInputError(message)
    checks: dict[str, tuple[str, ...]] = {}
    for stig_id, rules in table.items():
        _identifier(stig_id, STIG_ID, f"{where} key {clean_text(stig_id, 64)!r}")
        checked = _sorted_identifiers(rules, XCCDF_ID, f"{where}.{stig_id}")
        if not checked:
            message = f"{where}.{stig_id} must name at least one rule"
            raise InvalidInputError(message)
        checks[stig_id] = checked
    return MappingProxyType(checks)


def _profile(value: object, stream: dict[str, object], where: str) -> ProfileMapping:
    table = as_object(value, where)
    _exact(table, PROFILE_KEYS, where)
    checks = _checks(table["stig_ids"], f"{where}.stig_ids")
    unmapped = _sorted_identifiers(
        table["rules_without_stig_id"], XCCDF_ID, f"{where}.rules_without_stig_id"
    )
    mapped = {rule for rules in checks.values() for rule in rules}
    if mapped & set(unmapped):
        message = f"{where}: a rule is listed both with and without a STIG ID"
        raise InvalidInputError(message)
    return ProfileMapping(
        datastream=_identifier(stream["name"], NAME, "name"),
        file_name=_identifier(stream["file_name"], NAME, "file_name"),
        content_sha256=_identifier(stream["sha256"], SHA256, "sha256"),
        benchmark_id=_identifier(stream["benchmark_id"], XCCDF_ID, "benchmark_id"),
        benchmark_version=_identifier(stream["benchmark_version"], NAME, "benchmark_version"),
        profile_id=_identifier(table["profile_id"], XCCDF_ID, f"{where}.profile_id"),
        stig_release=_identifier(table["stig_release"], STIG_RELEASE, f"{where}.stig_release"),
        checks=checks,
        unmapped_rules=unmapped,
    )


def parse_mapping(data: bytes, path: str) -> StigMapping:
    """Return the mapping document ``data``, read from ``path``.

    Raises:
        InvalidInputError: If the document is not a valid mapping file.
    """
    document = as_object(load_json(data), "the STIG mapping")
    _exact(document, DOCUMENT_KEYS, "the STIG mapping")
    if document["schema_version"] != SCHEMA_VERSION:
        message = f"the STIG mapping must have schema_version {SCHEMA_VERSION}"
        raise InvalidInputError(message)
    profiles: list[ProfileMapping] = []
    for index, raw in enumerate(as_list(document["datastreams"], "datastreams")):
        stream = as_object(raw, f"datastreams[{index}]")
        _exact(stream, STREAM_KEYS, f"datastreams[{index}]")
        for number, item in enumerate(as_list(stream["profiles"], f"datastreams[{index}]")):
            profiles.append(_profile(item, stream, f"datastreams[{index}].profiles[{number}]"))
    keys = [(item.benchmark_id, item.profile_id) for item in profiles]
    if len(set(keys)) != len(keys):
        message = "the STIG mapping lists a benchmark and profile more than once"
        raise InvalidInputError(message)
    return StigMapping(path, tuple(profiles))


def load_mapping(path: Path) -> StigMapping:
    """Read and parse the mapping file ``path``.

    Raises:
        InvalidInputError: If the file cannot be read or is not a valid mapping file.
    """
    display = clean_text(str(path), 256)
    try:
        return parse_mapping(read_input(path, MAX_BYTES), display)
    except InvalidInputError as error:
        message = f"the STIG mapping {display}: {error}"
        raise InvalidInputError(message) from None


def release_of(version: str, release_info: str) -> str | None:
    """Return the DISA release ``V<n>R<n>`` that DISA content states, or ``None``.

    DISA SCAP benchmarks write the version as ``<version>.<release>[.<n>]`` (``001.005.007``
    for V1R5); XCCDF STIG benchmarks write the version alone (``1``) and the release in the
    ``release-info`` text (``Release: 5 Benchmark Date: ...``). Anything else states no release.
    """
    dotted = re.fullmatch(r"([0-9]{1,3})\.([0-9]{1,3})(?:\.[0-9]{1,6})*", version)
    if dotted is not None:
        return f"V{int(dotted.group(1))}R{int(dotted.group(2))}"
    released = re.search(r"\bRelease:\s*([0-9]{1,3})\b", release_info)
    if re.fullmatch(r"[0-9]{1,3}", version) and released is not None:
        return f"V{int(version)}R{int(released.group(1))}"
    return None
