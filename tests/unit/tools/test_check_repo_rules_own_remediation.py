def findings(root: Path, relative: str, content: str | bytes) -> list[str]:
    target = root / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    data = content.encode() if isinstance(content, str) else content
    target.write_bytes(data)
    return [
        violation.message
        for violation in rules.check_file(target, root)
        if ADR in violation.message and "0025" in violation.message
    ]


def assert_refused(messages: list[str], expected: str) -> None:
    assert any(expected in message for message in messages), messages


