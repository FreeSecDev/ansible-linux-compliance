"""Differential test of the XCCDF results parser (FREES-126).

``tests/fixtures/differential/openscap-results.json`` holds what the old
parser (the one in ``openscap.py`` before it moved onto ``xmlsafe``) returned
for every XML fixture of the repository: the extracted results, or the error
class and message. The file was generated by running :func:`observe` against
``main`` at commit fdc788c, and the entries for the reporting fixtures added by
FREES-75 against ``main`` at ff7b706, whose ``openscap.py`` is unchanged. It is
never regenerated from the code under test. This module passes on those
commits and after the refactor, so the two parsers behave identically on every
fixture, read path, chunk size and bound below. A fixture added later fails
:func:`test_the_expected_data_covers_every_fixture` until its entry is
recorded from the old parser.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import TYPE_CHECKING, cast

import pytest

from ansible_collections.freesecdev.linux_compliance.plugins.module_utils.compliance import (
    openscap,
    xmlsafe,
)

if TYPE_CHECKING:
    from collections.abc import Callable

FIXTURES = Path(__file__).resolve().parents[4] / "fixtures"
EXPECTED = FIXTURES / "differential" / "openscap-results.json"
HEX_SUFFIX = ".xml.hex"
LARGE = 10**8
CHUNK_SIZES = (7, 64)


def fixture_names() -> list[str]:
    names = [
        path.relative_to(FIXTURES).as_posix()
        for path in FIXTURES.rglob("*")
        if path.is_file() and (path.suffix == ".xml" or path.name.endswith(HEX_SUFFIX))
    ]
    return sorted(names)


def fixture_bytes(name: str) -> bytes:
    path = FIXTURES / name
    if name.endswith(HEX_SUFFIX):
        return bytes.fromhex(path.read_text(encoding="ascii").strip())
    return path.read_bytes()


def summary(parsed: openscap.ParsedResults) -> dict[str, object]:
    return {
        "benchmark_id": parsed.benchmark_id,
        "benchmark_version": parsed.benchmark_version,
        "profile_id": parsed.profile_id,
        "started_at": parsed.started_at,
        "finished_at": parsed.finished_at,
        "findings": [finding.to_dict() for finding in parsed.findings],
    }


def outcome(call: Callable[[], openscap.ParsedResults]) -> dict[str, object]:
    try:
        parsed = call()
    except openscap.XccdfParseError as error:
        return {"error": type(error).__name__, "message": str(error)}
    return {"result": summary(parsed)}


def set_chunk_size(monkeypatch: pytest.MonkeyPatch, size: int) -> None:
    monkeypatch.setattr(openscap, "READ_CHUNK_BYTES", size, raising=False)
    monkeypatch.setattr(xmlsafe, "READ_CHUNK_BYTES", size, raising=False)


def observe_fixture(
    name: str, directory: Path, monkeypatch: pytest.MonkeyPatch
) -> dict[str, dict[str, object]]:
    data = fixture_bytes(name)
    path = directory / Path(name).name.removesuffix(".hex")
    path.write_bytes(data)
    document = data.decode("utf-8", "surrogateescape")
    observed = {
        "text": outcome(lambda: openscap.parse_results(document)),
        "text-max-elements-5": outcome(
            lambda: openscap.parse_results(document, limits=openscap.XmlLimits(max_elements=5))
        ),
        "text-max-depth-3": outcome(
            lambda: openscap.parse_results(document, limits=openscap.XmlLimits(max_depth=3))
        ),
        "file": outcome(lambda: openscap.read_results(str(path), LARGE)),
        "file-one-byte-short": outcome(lambda: openscap.read_results(str(path), len(data) - 1)),
        "file-max-elements-5": outcome(
            lambda: openscap.read_results(
                str(path), LARGE, limits=openscap.XmlLimits(max_elements=5)
            )
        ),
    }
    for size in CHUNK_SIZES:
        with monkeypatch.context() as patch:
            set_chunk_size(patch, size)
            observed[f"file-chunks-{size}"] = outcome(
                lambda: openscap.read_results(str(path), LARGE)
            )
    return observed


def observe_paths(directory: Path) -> dict[str, dict[str, object]]:
    target = directory / "target.xml"
    target.write_bytes(fixture_bytes("xccdf/all-pass.xml"))
    link = directory / "link.xml"
    link.symlink_to(target)
    empty = directory / "empty.xml"
    empty.write_bytes(b"")
    return {
        "symlink": outcome(lambda: openscap.read_results(str(link), LARGE)),
        "directory": outcome(lambda: openscap.read_results(str(directory), LARGE)),
        "missing": outcome(lambda: openscap.read_results(str(directory / "missing.xml"), LARGE)),
        "empty-file": outcome(lambda: openscap.read_results(str(empty), LARGE)),
        "empty-text": outcome(lambda: openscap.parse_results("")),
        "lone-surrogate": outcome(lambda: openscap.parse_results("<a>\ud800</a>")),
    }


def observe(directory: Path, monkeypatch: pytest.MonkeyPatch) -> dict[str, object]:
    fixtures: dict[str, object] = {}
    for index, name in enumerate(fixture_names()):
        folder = directory / f"fixture-{index}"
        folder.mkdir()
        fixtures[name] = observe_fixture(name, folder, monkeypatch)
    paths = directory / "paths"
    paths.mkdir()
    return {"fixtures": fixtures, "paths": observe_paths(paths)}


def expected() -> dict[str, dict[str, object]]:
    data: dict[str, dict[str, object]] = json.loads(EXPECTED.read_text(encoding="utf-8"))
    return data


def normalised(value: object) -> object:
    result: object = json.loads(json.dumps(value, sort_keys=True))
    return result


def test_the_expected_data_covers_every_fixture() -> None:
    assert sorted(expected()["fixtures"]) == fixture_names()
    assert len(fixture_names()) >= 40


def test_the_expected_data_contains_results_and_rejections() -> None:
    fixtures = cast("dict[str, dict[str, dict[str, object]]]", expected()["fixtures"])
    entries = [entry for observed in fixtures.values() for entry in observed.values()]
    assert any("result" in entry for entry in entries)
    assert any("error" in entry for entry in entries)


@pytest.mark.parametrize("name", fixture_names())
def test_every_fixture_gives_the_recorded_result(
    name: str, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    observed = normalised(observe_fixture(name, tmp_path, monkeypatch))
    assert observed == expected()["fixtures"][name]


def test_path_handling_gives_the_recorded_result(tmp_path: Path) -> None:
    assert normalised(observe_paths(tmp_path)) == expected()["paths"]
