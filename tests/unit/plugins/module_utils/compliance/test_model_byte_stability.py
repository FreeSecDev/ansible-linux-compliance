"""Byte stability of findings documents without operator deviations (FREES-203).

``tests/fixtures/findings/serialization-digests.json`` holds the SHA-256 of
:func:`model.dumps` for scan runs built from every XCCDF results fixture that the
OpenSCAP parser and the model accept, in each form that existed before schema 1.3: plain
(1.0), off-platform (1.1), placed (1.2, with and without the marker), waived and
remediated. The file was generated by running :func:`observe` against ``main``
at commit 788c9ca, before the findings model gained operator deviations. It is
never regenerated from the code under test, so a run without a deviation keeps
the bytes, and therefore the evidence and evaluation digests, it had before.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import replace
from pathlib import Path
from typing import TYPE_CHECKING

import pytest

from ansible_collections.freesecdev.linux_compliance.plugins.module_utils.compliance import (
    model,
    openscap,
    placement,
)

if TYPE_CHECKING:
    from collections.abc import Callable

FIXTURES = Path(__file__).resolve().parents[4] / "fixtures"
EXPECTED = FIXTURES / "findings" / "serialization-digests.json"
EVALUATION = FIXTURES / "reporting" / "exceptions-evaluation.json"
HEX_SUFFIX = ".xml.hex"
CONTENT_SHA = "c" * 64
EXCEPTION = model.ExceptionStatus(
    model.ExceptionState.ACTIVE, "EXC-STABLE", "Accepted risk", "2099-01-01T00:00:00Z"
)
MARKER = model.OffPlatform(model.Platform("ubuntu", "24.04"), model.Platform("ubuntu", "26.04"))
PLACEMENT = placement.ControlPlacement(
    family="ssh",
    topic="ssh",
    tags=("auditd",),
    stig_id="UBTU-24-100820",
    mapped_rules=("xccdf_org.ssgproject.content_rule_sshd_disable_root_login",),
    partially_disabled_by=(),
)


def fixture_names() -> list[str]:
    names = [
        path.relative_to(FIXTURES).as_posix()
        for path in FIXTURES.rglob("*")
        if path.is_file() and (path.suffix == ".xml" or path.name.endswith(HEX_SUFFIX))
    ]
    return sorted(names)


def parsed(name: str) -> openscap.ParsedResults | None:
    path = FIXTURES / name
    if name.endswith(HEX_SUFFIX):
        data = bytes.fromhex(path.read_text(encoding="ascii").strip())
    else:
        data = path.read_bytes()
    try:
        results = openscap.parse_results(data.decode("utf-8", "surrogateescape"))
        build(results)
    except (openscap.XccdfParseError, model.ModelError):
        return None
    return results


def build(results: openscap.ParsedResults, *, version: str = "24.04") -> model.ScanRun:
    return model.ScanRun(
        run_id="run-stable",
        started_at=results.started_at,
        finished_at=results.finished_at,
        host=model.HostIdentity("web01", "ubuntu", version, "x86_64", None),
        scanner=model.ScannerInfo("openscap", "1.3.10"),
        content=model.Provenance("ssg-ubuntu2404-ds.xml", "0.1.82", CONTENT_SHA),
        benchmark_id=results.benchmark_id,
        profile_id=results.profile_id,
        status=model.ScanStatus.COMPLETED,
        error_message=None,
        findings=results.findings,
    )


def waived(finding: model.Finding) -> model.Finding:
    if finding.outcome is not model.Outcome.FAIL:
        return finding
    return replace(finding, outcome=model.Outcome.WAIVED, exception=EXCEPTION)


def remediated(finding: model.Finding) -> model.Finding:
    result = model.RemediationResult(
        finding.rule_id, model.RemediationStatus.APPLIED, True, "drop-in written"
    )
    return replace(finding, remediation=result)


def placed(run: model.ScanRun) -> model.ScanRun:
    first, *rest = run.findings
    return replace(run, findings=(replace(first, control=PLACEMENT), *rest))


def with_findings(
    run: model.ScanRun, change: Callable[[model.Finding], model.Finding]
) -> model.ScanRun:
    return replace(run, findings=tuple(change(item) for item in run.findings))


def variants(results: openscap.ParsedResults) -> dict[str, model.ScanRun]:
    plain = build(results)
    marked = replace(build(results, version="26.04"), off_platform=MARKER)
    found = {
        "plain": plain,
        "off_platform": marked,
        "waived": with_findings(plain, waived),
        "remediated": with_findings(plain, remediated),
    }
    if results.findings:
        found["placed"] = placed(plain)
        found["placed_off_platform"] = placed(marked)
    return found


def digest(run: model.ScanRun) -> str:
    return hashlib.sha256(model.dumps(run).encode("ascii")).hexdigest()


def accepted() -> dict[str, openscap.ParsedResults]:
    found: dict[str, openscap.ParsedResults] = {}
    for name in fixture_names():
        results = parsed(name)
        if results is not None:
            found[name] = results
    return found


def observe() -> dict[str, dict[str, str]]:
    return {
        name: {key: digest(run) for key, run in variants(results).items()}
        for name, results in accepted().items()
    }


def expected() -> dict[str, dict[str, str]]:
    data: dict[str, dict[str, str]] = json.loads(EXPECTED.read_text(encoding="utf-8"))
    return data


def test_the_recorded_digests_cover_every_accepted_fixture() -> None:
    found = accepted()
    assert sorted(expected()) == sorted(found)
    assert len(found) >= 8
    versions = {
        run.schema_version for results in found.values() for run in variants(results).values()
    }
    assert versions == {"1.0", "1.1", "1.2"}


@pytest.mark.parametrize("name", sorted(expected()))
def test_every_fixture_run_serializes_to_its_recorded_bytes(name: str) -> None:
    results = parsed(name)
    assert results is not None
    runs = variants(results)
    assert {key: digest(run) for key, run in runs.items()} == expected()[name]
    for run in runs.values():
        text = model.dumps(run)
        assert model.dumps(model.loads(text)) == text
        assert model.loads(text) == run


def test_the_evaluation_fixture_keeps_the_bytes_of_its_scan_run() -> None:
    document = json.loads(EVALUATION.read_text(encoding="utf-8"))
    run = model.ScanRun.from_dict(document["scan_run"])
    assert run.to_dict() == document["scan_run"]
    canonical = json.dumps(
        document["scan_run"], sort_keys=True, separators=(",", ":"), ensure_ascii=True
    )
    assert model.dumps(run) == canonical
